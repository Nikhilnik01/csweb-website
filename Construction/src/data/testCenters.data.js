/** Return only active centers sorted alphabetically */
export const getActiveTestCenters = () =>
  TEST_CENTERS.filter((c) => c.isActive).sort((a, b) =>
    a.title.localeCompare(b.title),
  );

/** Get test center titles only (for dropdowns) */
export const getTestCenterTitles = () =>
  getActiveTestCenters().map((c) => c.title);

/** Group by region for display */
export const getTestCentersByRegion = () => {
  const active = getActiveTestCenters();
  return active.reduce((acc, center) => {
    const region = center.title.startsWith("London") ? "London" : "UK Wide";
    if (!acc[region]) acc[region] = [];
    acc[region].push(center);
    return acc;
  }, {});
};
